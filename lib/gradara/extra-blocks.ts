import type { Definition, Port, Parameter } from './model';

const input = (id: string, name = id, side: Port['side'] = 'left'): Port => ({
  id,
  name,
  direction: 'input',
  domain: 'signal',
  side,
});
const output = (
  id: string,
  name = id,
  unit = '',
  side: Port['side'] = 'right',
): Port => ({ id, name, direction: 'output', domain: 'signal', side, unit });
const p = (
  id: string,
  name: string,
  value: number,
  unit = '',
  min?: number,
): Parameter => ({ id, name, value, unit, min });
const signal = (
  kind: string,
  name: string,
  symbol: string,
  ports: Port[],
  equations: string,
  parameters: Parameter[] = [],
  declarations = '',
  description = name,
  keywords: string[] = [],
): Definition => ({
  kind,
  name,
  symbol,
  domain: 'signal',
  description,
  ports,
  equations,
  parameters,
  declarations,
  keywords,
});

